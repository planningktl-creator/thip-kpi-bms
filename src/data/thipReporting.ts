export function getReportingCadence(code: string): ThipReportingCadence {
  const cadence = thipReportingCadenceByCode[code];
  if (!cadence) throw new Error(`No THIP reporting cadence registered for ${code}`);
  return cadence;
}

export function getExpectedFiscalMonths(code: string): readonly number[] {
  return expectedFiscalMonthsByCadence[getReportingCadence(code)];
}

/**
 * Selects the latest applicable reporting period at or before a dashboard
 * fiscal-month selection. This keeps annual/quarterly KPIs visible without
 * pretending that they produced a result in a non-reporting month.
 */
export function getLatestApplicableFiscalMonth(code: string, selectedFiscalMonth: number): number {
  const expectedMonths = getExpectedFiscalMonths(code);
  return expectedMonths.filter((month) => month <= selectedFiscalMonth).at(-1) ?? expectedMonths[0]!;
}

export function getPreviousApplicableFiscalMonth(code: string, fiscalMonth: number): number | null {
  const expectedMonths = getExpectedFiscalMonths(code);
  const index = expectedMonths.indexOf(fiscalMonth);
  return index > 0 ? expectedMonths[index - 1]! : null;
}
